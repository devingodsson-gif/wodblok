// Builds src/data/shapes.js from a folder of category folders full of SVG files (one shape per file, file name = shape name).
// Usage: node tools/build-shapes.mjs "<folder with the category folders>"
// Each SVG is a 100x100 box (viewBox -50 -50 100 100) whose shape is drawn as a mask: white parts show ink, black parts are carved away.
// The mask is flattened into the app's own form: FILL = ink, CUT = carved away (the background colour).
import {readdirSync, readFileSync, writeFileSync, statSync} from 'node:fs';
import {join, basename} from 'node:path';
import {SET as BASIC_SET} from './basic-shapes.mjs';   // 2.31.0: the Basic shapes set is made in code and always goes last

const root = process.argv[2];
if (!root) { console.error('Usage: node tools/build-shapes.mjs "<folder>"'); process.exit(1); }

const num = s => { const m = /^(\d+)\s+/.exec(s); return m ? +m[1] : 1e9; };
// Set and shape names follow the words rules (developer guide, Part 9 section 14; 2.29.0): sentence case and British spelling. Proper nouns stay as they are.
const KEEP = /^(Egypt|Greek|Christian|Bible|Fuji|Mount)$/;
const sentence = s => s.split(' ').map((w, i) => i === 0 || KEEP.test(w) ? w : w.toLowerCase()).join(' ');
const BRIT = [[/\bArmor\b/gi, m => m[0] === 'A' ? 'Armour' : 'armour'], [/\bTheater\b/gi, m => m[0] === 'T' ? 'Theatre' : 'theatre'], [/\bPlow\b/gi, m => m[0] === 'P' ? 'Plough' : 'plough'], [/\bColor/gi, m => m[0] === 'C' ? 'Colour' : 'colour'], [/\bGray\b/gi, m => m[0] === 'G' ? 'Grey' : 'grey']];
const words = s => BRIT.reduce((t, [r, f]) => t.replace(r, f), s);
const catName = s => words(sentence(s.replace(/^\d+\s+/, '').trim()));
const num2 = v => v;

function flatten(svg, file) {
  const m = /<mask\b[^>]*>([\s\S]*?)<\/mask>/.exec(svg);
  if (!m) throw new Error('no mask in ' + file);
  let inner = m[1].trim();
  const bg = /^<rect x="-50" y="-50" width="100" height="100" fill="#000"\/>/;
  if (!bg.test(inner)) throw new Error('unexpected mask start in ' + file);
  inner = inner.replace(bg, '');
  inner = inner.replace(/(fill|stroke)="#fff"/g, '$1="FILL"').replace(/(fill|stroke)="#000"/g, '$1="CUT"');
  if (/#[0-9a-f]{3,6}\b/i.test(inner)) throw new Error('unexpected colour in ' + file);
  return inner;
}

const cats = readdirSync(root).filter(d => statSync(join(root, d)).isDirectory())
  .sort((a, b) => num(a) - num(b) || a.localeCompare(b));
const out = [];
let n = 0;
for (const d of cats) {
  const files = readdirSync(join(root, d)).filter(f => f.toLowerCase().endsWith('.svg')).sort((a, b) => a.localeCompare(b, undefined, {numeric: true, sensitivity: 'base'}));
  const list = files.map(f => [words(basename(f, '.svg')), flatten(readFileSync(join(root, d, f), 'utf8'), join(d, f))]);
  n += list.length;
  out.push([catName(d), list]);
}
out.push(BASIC_SET); n += BASIC_SET[1].length;
const js = '// Built-in shapes. Generated by tools/build-shapes.mjs from the shape artwork; do not edit by hand.\n' +
  '// [[set name, [[shape name, svg markup with FILL (ink) and CUT (carved away) in a -50..50 box], ...]], ...]\n' +
  'const SHAPES=' + JSON.stringify(out) + ';\nexport {SHAPES};\n';
writeFileSync(new URL('../src/data/shapes.js', import.meta.url), js);
console.log(cats.length + ' sets, ' + n + ' shapes, ' + (js.length / 1024).toFixed(0) + ' KB');
