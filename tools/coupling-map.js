#!/usr/bin/env node
// Coupling map for the WODBLOK single-file build.
// Usage: node tools/coupling-map.js legacy/wodblok-v100.html > docs/coupling-map.md
// Parses the longest <script> block, then reports for every top-level name: its home section
// (the nearest preceding `// =====` marker), which other sections read it, and which write it.
// Pure analysis: deterministic output, no timestamps.
const fs = require('fs');
const espree = require('espree');
const eslintScope = require('eslint-scope');

const file = process.argv[2];
if (!file) { console.error('usage: coupling-map.js <file.html>'); process.exit(1); }
const html = fs.readFileSync(file, 'utf8');
const lines = html.split('\n');

// find the longest <script>...</script> block (line-based; the app's scripts are on their own lines)
const blocks = [];
for (let i = 0; i < lines.length; i++) {
  if (/^<script>/.test(lines[i])) {
    if (/<\/script>/.test(lines[i])) continue; // one-line script (theme pre-paint)
    let j = i + 1;
    while (j < lines.length && !/<\/script>/.test(lines[j])) j++;
    blocks.push({ start: i + 2, end: j }); // 1-based first body line .. last body line (exclusive of closing tag line)
    i = j;
  }
}
blocks.sort((a, b) => (b.end - b.start) - (a.end - a.start));
const { start: START, end: END } = blocks[0];
const src = lines.slice(START - 1, END).join('\n');

const ast = espree.parse(src, { ecmaVersion: 'latest', sourceType: 'script', loc: true, range: true });
const sm = eslintScope.analyze(ast, { ecmaVersion: 2022, sourceType: 'script' });
const g = sm.globalScope;

const marks = [];
lines.forEach((l, i) => { if (i + 1 >= START && i + 1 <= END && l.startsWith('// =====')) marks.push(i + 1); });
const secOf = abs => { let s = 0; for (const m of marks) if (m <= abs) s = m; return s; };
const secName = s => s ? lines[s - 1].replace(/^\/\/ =+\s*/, '').replace(/[|]/g, '/').slice(0, 44).trim() : '(core, before first marker)';
const abs = n => n.loc.start.line + START - 1;

// Guard: eslint-scope 8.x does not link references to global var/function declarations in script
// mode (they come back with 0 references), which silently under-counts coupling. 9.x does.
{
  const fnRefs = g.variables.filter(v => v.defs.length && v.defs[0].type === 'FunctionName').reduce((n, v) => n + v.references.length, 0);
  if (fnRefs === 0) { console.error('eslint-scope did not resolve global function references; use eslint-scope >= 9.1.2'); process.exit(2); }
}
const rows = [];
const kinds = {};
for (const v of g.variables) {
  if (!v.defs.length) continue;
  const d = v.defs[0];
  const kind = d.type === 'FunctionName' ? 'function' : d.type === 'Variable' ? d.parent.kind : d.type;
  kinds[kind] = (kinds[kind] || 0) + 1;
  const home = secOf(abs(d.name));
  const readers = new Set(), writers = new Set();
  let writes = 0;
  for (const r of v.references) {
    const s = secOf(abs(r.identifier));
    const isW = r.isWrite() && !r.init;
    if (isW) writes++;
    if (s !== home) (isW ? writers : readers).add(s);
  }
  rows.push({ name: v.name, kind, line: abs(d.name), home, readers, writers, writes });
}

const used = rows.filter(r => r.readers.size || r.writers.size);
const crossWritten = rows.filter(r => r.writers.size).sort((a, b) => b.writers.size - a.writers.size || b.writes - a.writes || a.name.localeCompare(b.name));
const reassigned = rows.filter(r => (r.kind === 'let' || r.kind === 'var') && r.writes > 0);

let out = '';
const P = s => { out += s + '\n'; };
P('# Coupling map');
P('');
P(`Generated by \`tools/coupling-map.js\` from \`${file}\`. Main script: lines ${START}-${END}. Sections are the \`// =====\` markers; names defined before the first marker are "(core)".`);
P('');
P('## Summary');
P('');
P(`- Top-level names: **${rows.length}** (${Object.entries(kinds).map(([k, n]) => `${n} ${k}`).join(', ')})`);
P(`- Section markers: **${marks.length}**`);
P(`- Names used outside their own section: **${used.length}**`);
P(`- let/var that are reassigned anywhere: **${reassigned.length}**`);
P(`- Names **reassigned from another section**: **${crossWritten.length}** (these cannot become ES module exports as-is; Phase 1b moves them onto a state object)`);
P('');
P('## Sections (by size)');
P('');
P('| Section | First line | Lines | Names defined |');
P('|---|---:|---:|---:|');
const secStarts = [0, ...marks];
const secRows = secStarts.map((m, i) => {
  const first = m || START;
  const next = secStarts[i + 1] || END + 1;
  return { name: secName(m), first, lines: next - first, defs: rows.filter(r => r.home === m).length };
});
secRows.sort((a, b) => b.lines - a.lines).forEach(s => P(`| ${s.name} | ${s.first} | ${s.lines} | ${s.defs} |`));
P('');
P('## Names reassigned from another section');
P('');
P('| Name | Kind | Defined at | Home section | Written from (sections) | Writes |');
P('|---|---|---:|---|---|---:|');
for (const r of crossWritten) P(`| \`${r.name}\` | ${r.kind} | ${r.line} | ${secName(r.home)} | ${[...r.writers].map(secName).sort().join('; ')} | ${r.writes} |`);
P('');
P('## Most widely read names (read from the most other sections)');
P('');
P('| Name | Kind | Home section | Read from N other sections |');
P('|---|---|---|---:|');
rows.filter(r => r.readers.size).sort((a, b) => b.readers.size - a.readers.size || a.name.localeCompare(b.name)).slice(0, 40)
  .forEach(r => P(`| \`${r.name}\` | ${r.kind} | ${secName(r.home)} | ${r.readers.size} |`));
P('');
P('## Window bridges (`window.wbX = ...`)');
P('');
const bridges = new Map();
const re = /window\.([A-Za-z_$][\w$]*)\s*=(?!=)/g;
lines.slice(START - 1, END).forEach((l, i) => { let m; while ((m = re.exec(l))) { const a = i + START; const e = bridges.get(m[1]) || []; e.push(a); bridges.set(m[1], e); } });
P(`${bridges.size} distinct names are assigned onto \`window\`:`);
P('');
P([...bridges.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([k, v]) => `\`${k}\` (${v.join(', ')})`).join(', '));
P('');
process.stdout.write(out);
