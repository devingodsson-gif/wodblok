#!/usr/bin/env node
// Copies fflate (MIT, (c) 101arrowz) from node_modules into src/vendor/fflate.js as one ES module, so the app has no runtime
// dependency and no bare imports. Usage: node tools/vendor-fflate.js   (re-run after changing the fflate version)
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'node_modules', 'fflate', 'esm', 'browser.js'), 'utf8');
const ver = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', 'fflate', 'package.json'), 'utf8')).version;
const body = src.replace(/^export \{[^}]*\};\n/gm, '').replace(/^export (function|var|const|let|class) /gm, '$1 ');
const out = `// fflate ${ver}, MIT licence, Copyright (c) 2023 Arjun Barrett. Generated by tools/vendor-fflate.js from node_modules/fflate/esm/browser.js; do not edit.\n${body}\nexport {zipSync,unzipSync,strToU8,strFromU8};\n`;
fs.mkdirSync(path.join(ROOT, 'src', 'vendor'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src', 'vendor', 'fflate.js'), out);
fs.copyFileSync(path.join(ROOT, 'node_modules', 'fflate', 'LICENSE'), path.join(ROOT, 'src', 'vendor', 'fflate.LICENSE'));
console.log('vendored fflate', ver, out.length + ' bytes');
